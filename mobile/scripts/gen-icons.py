#!/usr/bin/env python3
"""Write the icon set of the iPhone app from the desktop app's.

Reads `src/ui/icons.rs` (the drawings, the colours and the old emoji icons)
and writes `mobile/Core/Sources/RuneCore/IconData.swift`. Run it again when
an icon is added or changed on the desktop:

    python3 mobile/scripts/gen-icons.py
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "ui" / "icons.rs"
TARGET = ROOT / "mobile" / "Core" / "Sources" / "RuneCore" / "IconData.swift"


def section(text: str, start: str, end: str) -> str:
    a = text.index(start)
    return text[a : text.index(end, a)]


def swift_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")

    paths = section(text, "pub fn paths(", "\n}\n")
    icons = re.findall(r'"([a-z0-9-]+)"\s*=>\s*\{?\s*r#"(.*?)"#', paths, flags=re.S)
    if len(icons) < 60:
        print(f"only {len(icons)} icons found in {SOURCE}; the file's form changed", file=sys.stderr)
        return 1

    colors = re.findall(r'\("([a-z]+)",\s*"[A-Za-z]+"\)', section(text, "pub const ICON_COLORS", "];"))
    emoji = re.findall(r'\("([^"]+)",\s*"([a-z0-9-]+)",\s*"([a-z]+)"\)', section(text, "const LEGACY_EMOJI", "];"))
    page_icons = re.findall(r'"([a-z0-9-]+)"', section(text, "pub const PAGE_ICONS", "];"))

    out = [
        "// Generated by mobile/scripts/gen-icons.py from src/ui/icons.rs. Do not edit.",
        "",
        "enum IconData {",
        "    /// The SVG drawing of each icon, on a 24 by 24 grid.",
        "    static let markup: [String: String] = [",
    ]
    for name, markup in sorted(icons):
        out.append(f"        {swift_string(name)}: {swift_string(markup)},")
    out += ["    ]", "", "    /// Icon colours, in the order the desktop app offers them.", "    static let colors: [String] = ["]
    out += [f"        {swift_string(c)}," for c in colors]
    out += ["    ]", "", "    /// Icons offered for pages and callouts.", "    static let pageIcons: [String] = ["]
    out += [f"        {swift_string(n)}," for n in page_icons]
    out += ["    ]", "", "    /// Emoji that old workspaces stored as icons: emoji, icon, colour.", "    static let legacyEmoji: [(String, String, String)] = ["]
    out += [f"        ({swift_string(e)}, {swift_string(n)}, {swift_string(c)})," for e, n, c in emoji]
    out += ["    ]", "}", ""]

    TARGET.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(icons)} icons, {len(colors)} colours, {len(emoji)} emoji -> {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
